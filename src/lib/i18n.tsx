interface I18nContextType { locale: Locale; setLocale: (l: Locale) => void; t: (key: string, vars?: Record<string, string | number>) => string; }
const I18nContext = createContext<I18nContextType>({ locale: "id", setLocale: () => {}, t: (k) => k });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("id");
  useEffect(() => { const s = localStorage.getItem("locale") as Locale; if (s === "id" || s === "en") setLocaleState(s); }, []);
  function setLocale(l: Locale) { setLocaleState(l); localStorage.setItem("locale", l); }
  function t(key: string, vars?: Record<string, string | number>): string { let text = translations[locale][key] || translations["en"][key] || key; if (vars) { for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v)); } return text; }
  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() { return useContext(I18nContext); }
